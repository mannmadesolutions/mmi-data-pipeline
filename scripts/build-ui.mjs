/**
 * Builds the React admin UI (src/<entry>/index.tsx → build/<entry>.js) with esbuild.
 *
 * React is not bundled: imports of react, react-dom/client and react/jsx-runtime
 * resolve to the copies WordPress registers (handles react, react-dom,
 * react-jsx-runtime), the same way @wordpress/scripts does it. Each entry gets a
 * build/<entry>.asset.php with its script dependencies and a content hash, which
 * the PHP enqueue uses as the ?ver= so a changed build always busts caches.
 */
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ENTRIES = {
  // entry name: WordPress script handles it needs besides React's.
  workbench: ["jquery", "mmi-pipeline-rule-builder", "mmi-pagination", "mmi-nonce-refresh"],
};
const WP_GLOBALS = {
  react: { global: "React", handle: "react" },
  "react-dom": { global: "ReactDOM", handle: "react-dom" },
  "react-dom/client": { global: "ReactDOM", handle: "react-dom" },
  "react/jsx-runtime": { global: "ReactJSXRuntime", handle: "react-jsx-runtime" },
};

/** Maps WordPress-provided modules to their window globals and records which were used. */
function wpGlobals(used) {
  return {
    name: "wp-globals",
    setup(b) {
      b.onResolve({ filter: /^(react|react-dom|react-dom\/client|react\/jsx-runtime)$/ }, (args) => ({ path: args.path, namespace: "wp-global" }));
      b.onLoad({ filter: /.*/, namespace: "wp-global" }, (args) => {
        const g = WP_GLOBALS[args.path];
        used.add(g.handle);
        return { contents: `module.exports = window.${g.global};`, loader: "js" };
      });
    },
  };
}

for (const [entry, extraDeps] of Object.entries(ENTRIES)) {
  const used = new Set();
  const result = await build({
    entryPoints: [join(ROOT, "src", entry, "index.tsx")],
    bundle: true,
    write: false,
    format: "iife",
    target: "es2019",
    minify: true,
    legalComments: "none",
    jsx: "automatic",
    charset: "utf8",
    plugins: [wpGlobals(used)],
    logLevel: "warning",
  });
  const code = result.outputFiles[0].contents;
  const deps = [...[...used].sort(), ...extraDeps];
  const version = createHash("sha256").update(code).digest("hex").slice(0, 20);
  mkdirSync(join(ROOT, "build"), { recursive: true });
  writeFileSync(join(ROOT, "build", `${entry}.js`), code);
  writeFileSync(join(ROOT, "build", `${entry}.asset.php`),
    `<?php\n// Generated by scripts/build-ui.mjs. Do not edit.\nif ( ! defined( 'ABSPATH' ) ) {\n    exit;\n}\nreturn array( 'dependencies' => array( ${deps.map((d) => `'${d}'`).join(", ")} ), 'version' => '${version}' );\n`);
  console.log(`build/${entry}.js  ${(code.length / 1024).toFixed(1)} KB  ver ${version}  deps ${deps.join(", ")}`);
}
